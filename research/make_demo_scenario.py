#!/usr/bin/env python3
"""Сценарий демонстрации собирается из результатов прогона, а не пишется руками.

Источник цифр: research/results/demo_verified.json (его пишет verify_demo.py,
обращаясь к живому сервису) и research/results/service_path_extras.json.
Если порог или модель поменялись — перезапусти verify_demo.py и этот скрипт,
и в документе окажутся новые числа, а не старые обещания.

    python research/verify_demo.py && python research/make_demo_scenario.py
"""
import json
from pathlib import Path

HERE = Path('/opt/case17/app/research')
RES = HERE / 'results'
OUT = HERE / 'DEMO_SCENARIO.md'

CASES = {
    'лёгкий': dict(
        order=1,
        title='Лёгкий случай: машина найдена уверенно',
        why='Показываем, что базовый сценарий работает и выглядит понятно.',
        say='Оператор загрузил кадр, обвёл машину, нажал «найти». Первый кандидат — '
            'та же машина с другой камеры. Второй кандидат — тоже она, другим кадром. '
            'Уверенность видна числом, а не «похоже, подходит».',
        shot='pitch_assets/09_ui_search.png'),
    'сложный ракурс': dict(
        order=2,
        title='Сложный случай: другой ракурс, ответ у самого порога',
        why='Показываем, где проходит граница и что сервис её видит.',
        say='Тот же автомобиль с другого ракурса. Правильный ответ первый, но '
            'уверенность 0.51 при пороге 0.5114 — это ровно граница. На местах '
            'один и два стоит одна и та же машина, а на третьем уже чужая, и '
            'отрыв — половина процента. Именно так выглядит трудный случай: '
            'сервис его берёт, но мы видим, что запас нулевой.',
        shot='pitch_assets/13_ui_hard_viewpoint.png'),
    'ночь': dict(
        order=3,
        title='Ночной кадр плюс объяснение решения',
        why='Здесь же показываем карту вклада — главный ответ на вопрос про номер.',
        say='Тёмный кадр, тёмная машина. Находит. Дальше нажимаем «показать почему»: '
            'подсвечены участки кадра, которые дали сходство. Зона номерного знака '
            'не подсвечена — модель смотрит на кузов, стойки и фонари. Это не '
            'Grad-CAM, а разложение самой оценки сходства по участкам.',
        shot='pitch_assets/14_ui_night.png'),
    'без пары (отказ)': dict(
        order=4,
        title='Запрос без пары: сервис отказывается отвечать',
        why='Отказ — это 10% оценки и главное отличие продукта от ноутбука.',
        say='Этой машины в галерее нет — мы убрали все её кадры заранее. '
            'Сервис не выдаёт «лучшее из плохого», а честно говорит, что '
            'уверенного совпадения нет, и называет число: лучший кандидат и порог. '
            'Порог не выдуман — это максимум индекса Юдена на рабочем распределении.',
        shot='pitch_assets/15_ui_refusal.png'),
}


def main():
    ver = json.loads((RES / 'demo_verified.json').read_text())
    cases = json.loads((RES / 'demo_cases.json').read_text())
    by_label = {c['label']: c for c in cases}
    ex_path = RES / 'service_path_extras.json'
    thr = None
    if ex_path.exists():
        ex = json.loads(ex_path.read_text())
        thr = ex.get('refusal_deployment')

    L = []
    A = L.append
    A('# Сценарий демонстрации')
    A('')
    A('Пошагово: что открываем, что нажимаем, что говорим. Четыре запроса')
    A('подобраны заранее и прогнаны через живой сервис — файл')
    A('`research/results/demo_verified.json` содержит ответ сервиса на каждый.')
    A('')
    A('**Перед показом.** Поднять стенд и один раз прогреть модель, иначе первый')
    A('запрос займёт лишние секунды на загрузку весов:')
    A('')
    A('```bash')
    A('cp .env.example .env && docker compose up -d')
    A('curl -s localhost:8000/health                 # ждём status: ok')
    A('python research/verify_demo.py                # все четыре случая ещё живы')
    A('```')
    A('')
    A('Кадры для демонстрации лежат в `/opt/case17/data/crops/train/`, имена —')
    A('в таблицах ниже. Их удобно заранее скопировать на рабочий стол,')
    A('чтобы не искать во время показа.')
    A('')
    A('---')
    A('')

    ordered = sorted(ver, key=lambda r: CASES.get(r['label'], {}).get('order', 99))
    for n, r in enumerate(ordered, 1):
        meta = CASES.get(r['label'], {})
        src = by_label.get(r['label'], {})
        A(f"## Шаг {n}. {meta.get('title', r['label'])}")
        A('')
        A(f"**Зачем.** {meta.get('why', '')}")
        A('')
        A('| | |')
        A('|---|---|')
        A(f"| Файл кадра | `{r['image_id']}.jpg` |")
        if src.get('vehicle_id'):
            A(f"| Машина | {src['vehicle_id']} |")
        if src.get('brightness') is not None:
            A(f"| Яркость кадра | {src['brightness']} из 255 |")
        A('| Рамка | вся картинка: x=0, y=0, w и h по размеру кропа |')
        if r.get('refusal'):
            A(f"| Ответ сервиса | **отказ**: {r.get('message', '')} |")
        else:
            A(f"| Ответ сервиса | правильная машина на месте **{r.get('hit_rank')}**, "
              f"уверенность **{r.get('top1_conf'):.4f}** |")
        A(f"| Время ответа | {r.get('took_ms')} мс |")
        if r.get('explain', {}).get('grid'):
            A(f"| Объяснение | карта {r['explain']['grid']}×{r['explain']['grid']} "
              f"за {r['explain']['took_ms']} мс |")
        A(f"| Скриншот | `{meta.get('shot', '')}` |")
        A('')
        A(f"**Что сказать.** {meta.get('say', '')}")
        A('')

    A('---')
    A('')
    A('## Если спросят')
    A('')
    A('**«А это не по номеру?»** — Нажимаем «показать почему» на любом кадре.')
    A('Зона номера в подсветке не участвует. В коде нет ни OCR, ни детектора')
    A('текста — это проверяется поиском по репозиторию за десять секунд.')
    A('')
    A('**«Откуда порог?»** — Открываем `pitch_assets/05_refusal.png`: два')
    A('распределения максимального сходства, с парой в галерее и без пары.')
    if thr:
        A(f"Порог — максимум индекса Юдена: {thr['balanced']['threshold']}, "
          f"F1 {thr['balanced']['f1']}, полнота {thr['balanced']['recall']}, "
          f"TNR {thr['balanced']['TNR']}. Строгий режим: {thr['strict']['threshold']}, "
          f"TNR {thr['strict']['TNR']}.")
    A('')
    A('**«Заработает ли на миллионе?»** — `research/ANN.md`: это замер, а не оценка.')
    A('HNSW отвечает за 0.41 мс против 137 мс точного перебора, теряя 0.26 mAP.')
    A('')
    A('**«Почему галерея в демо маленькая?»** — В демо-галерее только размеченные')
    A('кадры отложенных машин, чтобы каждое «это та же машина» можно было')
    A('проверить по `vehicle_id` прямо на экране. На полной галерее сервис')
    A('работает так же, метрики — в `docs/SUBMISSION_README.md`.')
    A('')
    A('## Чего на демонстрации не делаем')
    A('')
    A('* Не загружаем случайные фото из интернета: галерея собрана из выборки')
    A('  заказчика, и совпадения там быть не должно — это выглядит как провал,')
    A('  хотя это правильный отказ.')
    A('* Не показываем первый запрос после подъёма контейнеров: он включает')
    A('  загрузку весов и вводит в заблуждение по времени.')
    A('* Не называем цифр, которых нет в `research/results/`.')
    A('')

    OUT.write_text('\n'.join(L))
    print(f'записано: {OUT}  ({len(L)} строк)')


if __name__ == '__main__':
    main()
